const LANG_COOKIE = "portal-lang";

function getCookieLang(): Language {
  if (typeof document === "undefined") return "en";
  const match = document.cookie.match(/(?:^|;\s*)portal-lang=([^;]+)/);
  return match?.[1] === "ar" ? "ar" : "en";
}

function setCookieLang(lang: Language) {
  document.cookie = `${LANG_COOKIE}=${lang}; path=/; max-age=${60 * 60 * 24 * 365}; SameSite=Lax`;
}

const LanguageContext = createContext<LanguageContextType | undefined>(
  undefined
);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguage] = useState<Language>("en");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    const saved = getCookieLang();
    setLanguage(saved);
    document.documentElement.lang = saved;
    document.documentElement.dir = saved === "ar" ? "rtl" : "ltr";
    setMounted(true);
  }, []);

  const toggleLanguage = () => {
    const next: Language = language === "en" ? "ar" : "en";
    setLanguage(next);
    setCookieLang(next);
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ar" ? "rtl" : "ltr";
  };

  const isRTL = language === "ar";
  const t = translations[language];

  if (!mounted) {
    return (
      <LanguageContext.Provider
        value={{
          language: "en",
          toggleLanguage: () => {},
          isRTL: false,
          t: translations.en,
        }}
      >
        <div style={{ visibility: "hidden" }}>{children}</div>
      </LanguageContext.Provider>
    );
  }

  return (
    <LanguageContext.Provider value={{ language, toggleLanguage, isRTL, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context)
    throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
